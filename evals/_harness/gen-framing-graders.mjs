// Generate the "framing copied verbatim" graders of the discuss eval cases (discuss ticket 08).
//   node evals/_harness/gen-framing-graders.mjs          write the grader files
//   node evals/_harness/gen-framing-graders.mjs --check  exit 1 when any grader is out of date
// Each grader is a regex that must find the whole framing file (round-1.md in round 1's prompt,
// round-n.md in round 2's) in the prompt the stub received; line endings may be LF or CRLF.
// Rerun after editing a framing file; discuss-skill-graders.test.mjs fails while they are stale.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const harness = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(harness, "..", "..");
const framing = path.join(repo, "skills", "discuss", "prompts", "framing");

// Cases whose stub replies always lead to a round 2 (the disputed Redis C3 is never conceded in round 1).
export const CASES = ["discuss-early-consensus", "discuss-limit-reached", "discuss-claude-first", "discuss-rounds-arg-no-question",
  "discuss-headless-default", "discuss-round-fails", "discuss-unstructured-ends", "discuss-user-call",
  "discuss-user-call-accept-false", "discuss-user-call-lapse"];
export const GRADERS = [
  { name: "round-1-framing-verbatim", source: "round-1.md", record: ".stub/exec-stdin.1.txt" },
  { name: "round-2-framing-verbatim", source: "round-n.md", record: ".stub/exec-stdin.2.txt" },
];

export function patternFor(text) {
  const body = text.replace(/\r\n/g, "\n").replace(/\s+$/, "");
  return body.split("\n").map((line) => line.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("\\r?\\n");
}

export function graderFile(g) {
  const pattern = patternFor(fs.readFileSync(path.join(framing, g.source), "utf8")).replace(/'/g, "''");
  return [
    "---",
    "type: regex",
    `pattern: '${pattern}'`,
    "target:",
    "  source: file",
    `  path: ${g.record}`,
    "---",
    "",
    `The whole of \`skills/discuss/prompts/framing/${g.source}\` appears verbatim in this round's prompt (LF or CRLF line endings): the skill copies the framing, never shortens or paraphrases it (discuss ticket 08). Generated by \`evals/_harness/gen-framing-graders.mjs\`; regenerate after editing the framing.`,
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const c of CASES) for (const g of GRADERS) {
    const file = path.join(repo, "evals", c, "graders", `${g.name}.md`);
    const want = graderFile(g);
    const have = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
    if (have === want) continue;
    if (check) { stale++; console.log(`stale: ${path.relative(repo, file)}`); } else fs.writeFileSync(file, want);
  }
  if (check && stale) process.exit(1);
  console.log(check ? "framing graders up to date" : `wrote ${CASES.length * GRADERS.length} framing graders`);
}
